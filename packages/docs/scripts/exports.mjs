import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const root = resolve(import.meta.dirname, "..");

export async function renderExports() {
  const config = JSON.parse(await readFile(resolve(root, "docs.json"), "utf8"));
  const summary = ["# Factorize", "", "Hosted workflow: connect your agent → create a job → run it → inspect the result → automate it.", "", "Application: https://app.factorize.sh", "MCP (Streamable HTTP + OAuth): https://app.factorize.sh/mcp", "", "Browser: email/password signup, verification, execution/provider connections and consent.", "MCP: discover targets, manage jobs, invoke with retained idempotency keys, inspect state/context/diagnostics.", "Current MCP does not return execution output; inspect browser traces or REST trace pages. REST is not full MCP parity.", ""];
  const full = [...summary, "Generated from maintained guides in navigation order. Do not edit this file directly.", ""];
  for (const group of config.navigation.groups) {
    summary.push(`## ${group.group}`, "");
    for (const entry of group.pages) {
      if (typeof entry !== "string") {
        summary.push(`- [${entry.group}](https://docs.factorize.sh/openapi.yaml): Complete generated REST schemas and operations`);
        full.push("## REST operations", "Contract: https://docs.factorize.sh/openapi.yaml", "The site renders this exact generated contract under Reference → REST operations.", "");
        continue;
      }
      const name = entry;
      const source = await readFile(resolve(root, `${name}.mdx`), "utf8");
      const match = source.match(/^---\n([\s\S]*?)\n---\n/);
      if (!match) throw new Error(`Missing frontmatter: ${name}`);
      const title = match[1].match(/^title: (.+)$/m)?.[1];
      const description = match[1].match(/^description: (.+)$/m)?.[1];
      summary.push(`- [${title}](https://docs.factorize.sh/${name === "index" ? "" : name}): ${description}`);
      const body = source.slice(match[0].length)
        .replace(/<CardGroup[^>]*>|<\/CardGroup>/g, "")
        .replace(/<Card[^>]*title="([^"]+)"[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/Card>/g, "[$1]($2): $3")
        .replace(/\]\(\/(?!\/)([^)]+)\)/g, "](https://docs.factorize.sh/$1)");
      full.push(`## ${title}`, `Source: https://docs.factorize.sh/${name === "index" ? "" : name}`, "", body.trim(), "");
    }
    summary.push("");
  }
  summary.push("## Machine-readable REST reference", "", "- https://docs.factorize.sh/openapi.yaml", "- https://docs.factorize.sh/llms-full.txt", "");
  return { "llms.txt": summary.join("\n"), "llms-full.txt": full.join("\n") };
}

export async function syncExports(check = false) {
  for (const [name, content] of Object.entries(await renderExports())) {
    if (check) {
      if (await readFile(resolve(root, name), "utf8") !== content) throw new Error(`${name} is stale; run npm run generate --workspace=factorize-docs`);
    } else await writeFile(resolve(root, name), content);
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await syncExports(process.argv.includes("--check"));
