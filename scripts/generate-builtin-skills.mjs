import {readFile, readdir, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {parseDocument} from 'yaml';

const root=fileURLToPath(new URL('../',import.meta.url));
export const skillNames=['grant-vm-access','manage-triggers','use-an-api'];
export async function renderBuiltinSkills(directory=resolve(root,'skills')) {
  const directories=(await readdir(directory,{withFileTypes:true})).filter(entry=>entry.isDirectory()).map(entry=>entry.name).sort();
  if(JSON.stringify(directories)!==JSON.stringify([...skillNames].sort()))throw new Error('Unexpected built-in workflow directories');
  const entries=[];
  for(const name of skillNames){
    const text=await readFile(resolve(directory,name,'SKILL.md'),'utf8');
    const header=/^---\n([\s\S]*?)\n---\n/.exec(text);
    if(!header)throw new Error(`Missing frontmatter: ${name}`);
    const doc=parseDocument(header[1],{uniqueKeys:true}),frontmatter=doc.toJS({maxAliasCount:0});
    if(doc.errors.length||frontmatter?.name!==name||typeof frontmatter.description!=='string'||!frontmatter.description.trim()||frontmatter.description.length>1024)throw new Error(`Invalid frontmatter: ${name}`);
    entries.push({name,frontmatter,text,digest:'sha256:'+createHash('sha256').update(text).digest('hex'),size:Buffer.byteLength(text)});
  }
  const version=createHash('sha256').update(JSON.stringify(entries)).digest('hex');
  return '// Generated by scripts/generate-builtin-skills.mjs; edit skills/*/SKILL.md.\n'+
    `export const builtinSkillsVersion = ${JSON.stringify(version)};\nexport const builtinSkillDocuments = ${JSON.stringify(entries,null,2)} as const;\n`;
}
export async function generateBuiltinSkills({check=false,output=resolve(root,'packages/api/src/generated/builtin-skills.ts'),directory}={}){
  const source=await renderBuiltinSkills(directory);
  if(check){if(await readFile(output,'utf8')!==source)throw new Error('Built-in skill drift: run npm run generate:skills');}
  else await writeFile(output,source);
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await generateBuiltinSkills({check:process.argv.includes('--check')});
